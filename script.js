function setYear(year) {
    currentYear = year;
    document.querySelectorAll('.year-btn').forEach(btn => {
        btn.classList.toggle('active', btn.dataset.year === year);
    });
    currentTomo = null;
    generateTomoButtons();
    updateCurrentSelector();
    renderCourses();
}

function generateTomoButtons() {
    tomoButtonsContainer.innerHTML = '';
    if (!currentYear) return;

    const yearData = driveLinks[currentYear];
    if (!yearData) return;

    tomos.forEach(tomo => {
        let hasData = false;
        for (const grade of grades) {
            const gradeData = yearData[grade.id];
            if (gradeData && gradeData[tomo.id] && Object.keys(gradeData[tomo.id]).length > 0) {
                hasData = true;
                break;
            }
        }

        const card = document.createElement('button');
        card.className = `tomo-card ${currentTomo === tomo.id ? 'active' : ''}`;
        card.dataset.id = tomo.id;
        card.style.setProperty('--tomo-color', tomo.color);
        card.disabled = !hasData;
        card.innerHTML = `
            <div class="tomo-card-badge">${tomo.roman}</div>
            <div class="tomo-card-icon">
                <i class="${tomo.icon}"></i>
            </div>
            <div class="tomo-card-title">${tomo.name}</div>
            <div class="tomo-card-desc">${hasData ? 'Ver cursos' : 'Sin material'}</div>
        `;

        card.addEventListener('click', () => {
            if (!hasData) return;
            currentTomo = tomo.id;
            generateTomoButtons();
            updateCurrentSelector();
            renderCourses();
            coursesContainer.scrollIntoView({ behavior: 'smooth', block: 'start' });
        });
        tomoButtonsContainer.appendChild(card);
    });
}

function updateCurrentSelector() {
    if (!currentTomo) {
        currentSelectorSpan.innerHTML = `<i class="fas fa-layer-group"></i><span>Selecciona un tomo para comenzar</span>`;
        return;
    }
    const tomoName = tomos.find(t => t.id === currentTomo)?.name || currentTomo;
    currentSelectorSpan.innerHTML = `<i class="fas fa-layer-group"></i><span>${tomoName}</span>`;
}

function renderCourses() {
    coursesContainer.innerHTML = '';
    if (!currentYear || !currentTomo) {
        coursesContainer.innerHTML = `
            <div class="empty-state">
                <i class="fas fa-book-open"></i>
                <p>Selecciona un tomo para ver los cursos</p>
            </div>
        `;
        coursesCountSpan.textContent = '0';
        return;
    }

    const yearData = driveLinks[currentYear];
    if (!yearData) {
        coursesContainer.innerHTML = `<div class="empty-state"><p>No hay datos para el año ${currentYear}.</p></div>`;
        coursesCountSpan.textContent = '0';
        return;
    }

    // Recolectar cursos únicos del tomo seleccionado en todos los grados
    const courseMap = new Map();

    grades.forEach(grade => {
        const links = yearData[grade.id]?.[currentTomo];
        if (!links) return;

        courses.forEach(course => {
            const hasLink = links[course.id] !== undefined && links[course.id] !== "";
            if (!hasLink) return;

            const available = !course.availableGrades || course.availableGrades.includes(grade.id);
            if (!available) return;

            if (!courseMap.has(course.id)) {
                courseMap.set(course.id, { course, link: links[course.id] });
            }
        });
    });

    const availableCourses = Array.from(courseMap.values());
    coursesCountSpan.textContent = availableCourses.length;

    if (availableCourses.length === 0) {
        coursesContainer.innerHTML = `<div class="empty-state"><i class="fas fa-folder-open"></i><p>No hay materiales disponibles para este tomo.</p></div>`;
        return;
    }

    availableCourses.forEach(({ course, link }, index) => {
        const areaColor = areaColors[course.area];
        const areaName = areaNames[course.area];
        const card = document.createElement('div');
        card.className = 'course-card';
        card.style.setProperty('--area-color', areaColor);
        card.style.setProperty('--course-color', course.color);
        card.style.animationDelay = `${index * 40}ms`;

        card.innerHTML = `
            <div class="course-card-header">
                <div class="course-icon">
                    <i class="${course.icon}"></i>
                </div>
                <div class="course-tags">
                    <span class="area-badge" style="background-color: ${areaColor};">${areaName}</span>
                    <span class="year-badge">${currentYear}</span>
                </div>
            </div>
            <div class="course-body">
                <h3>${course.name}</h3>
                <p>${course.description}</p>
            </div>
            <a href="${link}" target="_blank" class="drive-btn">
                <i class="fab fa-google-drive"></i>
                <span>Acceder al material</span>
            </a>
        `;
        coursesContainer.appendChild(card);
    });
}

